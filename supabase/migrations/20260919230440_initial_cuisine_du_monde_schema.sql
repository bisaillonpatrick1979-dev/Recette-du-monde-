create function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, avatar_path, country_code)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'display_name', new.raw_user_meta_data->>'full_name'),
    new.raw_user_meta_data->>'avatar_url',
    new.raw_user_meta_data->>'country_code'
  )
  on conflict (id) do nothing;

  insert into public.user_preferences (user_id, language_code, country_code, currency_code)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'language_code', 'fr'),
    coalesce(new.raw_user_meta_data->>'country_code', 'CA'),
    coalesce(new.raw_user_meta_data->>'currency_code', 'CAD')
  )
  on conflict (user_id) do nothing;

  insert into public.entitlements (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

revoke all on function private.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

