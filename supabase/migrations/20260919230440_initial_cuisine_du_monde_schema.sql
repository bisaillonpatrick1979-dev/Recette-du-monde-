create table public.recipes (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text,
  source_language text not null default 'en',
  country_code text,
  region text,
  category text,
  authenticity public.recipe_authenticity not null default 'adapted',
  status public.recipe_status not null default 'draft',
  difficulty public.recipe_difficulty,
  prep_minutes integer,
  cook_minutes integer,
  servings numeric(8,2),
  cover_image_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  constraint recipes_title_length check (char_length(title) between 2 and 180),
  constraint recipes_description_length check (description is null or char_length(description) <= 5000),
  constraint recipes_prep_nonnegative check (prep_minutes is null or prep_minutes >= 0),
  constraint recipes_cook_nonnegative check (cook_minutes is null or cook_minutes >= 0),
  constraint recipes_servings_positive check (servings is null or servings > 0)
);

